  DROP CONSTRAINT IF EXISTS uq_finanzas_movimientos_hash,
  DROP CONSTRAINT IF EXISTS uq_finanzas_estados_cuenta_importados_movimientos_hash;

CREATE INDEX IF NOT EXISTS ix_finanzas_estados_cuenta_importados_empresa_cuenta
  ON public.finanzas_estados_cuenta_importados (empresa_id, cuenta_id, fecha_creacion);
CREATE UNIQUE INDEX IF NOT EXISTS uq_finanzas_estados_cuenta_importados_empresa_hash_normal
  ON public.finanzas_estados_cuenta_importados (empresa_id, hash_archivo)
  WHERE es_historica = false;
CREATE INDEX IF NOT EXISTS ix_finanzas_estados_cuenta_importados_movimientos_empresa_fecha
  ON public.finanzas_estados_cuenta_importados_movimientos (empresa_id, cuenta_id, fecha);
CREATE INDEX IF NOT EXISTS ix_finanzas_estados_cuenta_importados_movimientos_estado
  ON public.finanzas_estados_cuenta_importados_movimientos (empresa_id, estado_revision);
CREATE UNIQUE INDEX IF NOT EXISTS uq_finanzas_estados_cuenta_importados_movimientos_hash_normal
  ON public.finanzas_estados_cuenta_importados_movimientos (empresa_id, cuenta_id, hash_movimiento)
  WHERE es_historico = false;
CREATE INDEX IF NOT EXISTS ix_finanzas_estados_cuenta_importados_relaciones_operacion
  ON public.finanzas_estados_cuenta_importados_relaciones (empresa_id, operacion_id);

