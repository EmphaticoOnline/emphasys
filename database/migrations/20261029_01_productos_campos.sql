-- Migración: valores de campos configurables de productos (texto, número, fecha, booleano).
-- Igual que public.contactos_campos, pero con llave foránea real a public.productos.
-- Los campos de tipo LISTA siguen guardándose en core.entidades_catalogos (por eso no hay catalogo_id aquí).

-- La llave foránea compuesta (empresa_id, producto_id) necesita un único sobre productos (empresa_id, id).
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                  WHERE conrelid = 'public.productos'::regclass AND conname = 'uq_productos_empresa_id') THEN
    ALTER TABLE public.productos ADD CONSTRAINT uq_productos_empresa_id UNIQUE (empresa_id, id);
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.productos_campos (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id    integer NOT NULL,
    producto_id   integer NOT NULL,
    campo_id      integer NOT NULL,
    valor_texto   text,
    valor_numero  numeric,
    valor_fecha   date,
    valor_boolean boolean,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_pc_producto FOREIGN KEY (empresa_id, producto_id)
        REFERENCES public.productos (empresa_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_pc_campo FOREIGN KEY (campo_id) REFERENCES core.campos_configuracion (id),
    CONSTRAINT ck_pc_un_solo_valor CHECK (
        (valor_texto IS NOT NULL)::int + (valor_numero IS NOT NULL)::int +
        (valor_fecha IS NOT NULL)::int + (valor_boolean IS NOT NULL)::int = 1)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_productos_campos_empresa_producto_campo ON public.productos_campos (empresa_id, producto_id, campo_id);
CREATE INDEX IF NOT EXISTS idx_productos_campos_producto ON public.productos_campos (producto_id);
CREATE INDEX IF NOT EXISTS idx_productos_campos_campo ON public.productos_campos (campo_id);

DROP TRIGGER IF EXISTS trg_productos_campos_updated_at ON public.productos_campos;
CREATE TRIGGER trg_productos_campos_updated_at BEFORE UPDATE ON public.productos_campos
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

COMMENT ON TABLE  public.productos_campos IS 'Valores capturados de campos dinámicos (texto, número, fecha, booleano) asociados a productos. Los campos tipo lista se guardan en core.entidades_catalogos.';
COMMENT ON COLUMN public.productos_campos.empresa_id IS 'Empresa propietaria del registro; debe coincidir con la del producto.';
COMMENT ON COLUMN public.productos_campos.producto_id IS 'Producto al que pertenece el valor.';
COMMENT ON COLUMN public.productos_campos.campo_id IS 'Campo configurado en core.campos_configuracion (entidad PRODUCTO).';
COMMENT ON COLUMN public.productos_campos.valor_texto IS 'Valor cuando el tipo de dato es texto.';
COMMENT ON COLUMN public.productos_campos.valor_numero IS 'Valor cuando el tipo de dato es numérico.';
COMMENT ON COLUMN public.productos_campos.valor_fecha IS 'Valor cuando el tipo de dato es fecha.';
COMMENT ON COLUMN public.productos_campos.valor_boolean IS 'Valor cuando el tipo de dato es booleano.';
