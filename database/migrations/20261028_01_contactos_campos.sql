-- Migración: valores de campos configurables de contactos (texto, número, fecha, booleano).
-- Mismo patrón que public.documentos_campos, pero con llave foránea real a public.contactos.
-- Los campos de tipo LISTA siguen guardándose en core.entidades_catalogos (por eso no hay catalogo_id aquí).

CREATE TABLE IF NOT EXISTS public.contactos_campos (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id    integer NOT NULL,
    contacto_id   integer NOT NULL,
    campo_id      integer NOT NULL,
    valor_texto   text,
    valor_numero  numeric,
    valor_fecha   date,
    valor_boolean boolean,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_cc_contacto FOREIGN KEY (empresa_id, contacto_id)
        REFERENCES public.contactos (empresa_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_cc_campo FOREIGN KEY (campo_id) REFERENCES core.campos_configuracion (id),
    CONSTRAINT ck_cc_un_solo_valor CHECK (
        (valor_texto IS NOT NULL)::int + (valor_numero IS NOT NULL)::int +
        (valor_fecha IS NOT NULL)::int + (valor_boolean IS NOT NULL)::int = 1)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_contactos_campos_empresa_contacto_campo ON public.contactos_campos (empresa_id, contacto_id, campo_id);
CREATE INDEX IF NOT EXISTS idx_contactos_campos_contacto ON public.contactos_campos (contacto_id);
CREATE INDEX IF NOT EXISTS idx_contactos_campos_campo ON public.contactos_campos (campo_id);

DROP TRIGGER IF EXISTS trg_contactos_campos_updated_at ON public.contactos_campos;
CREATE TRIGGER trg_contactos_campos_updated_at BEFORE UPDATE ON public.contactos_campos
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

COMMENT ON TABLE  public.contactos_campos IS 'Valores capturados de campos dinámicos (texto, número, fecha, booleano) asociados a contactos. Los campos tipo lista se guardan en core.entidades_catalogos.';
COMMENT ON COLUMN public.contactos_campos.empresa_id IS 'Empresa propietaria del registro; debe coincidir con la del contacto.';
COMMENT ON COLUMN public.contactos_campos.contacto_id IS 'Contacto (cliente, proveedor, vendedor, etc.) al que pertenece el valor.';
COMMENT ON COLUMN public.contactos_campos.campo_id IS 'Campo configurado en core.campos_configuracion (entidad CONTACTO).';
COMMENT ON COLUMN public.contactos_campos.valor_texto IS 'Valor cuando el tipo de dato es texto.';
COMMENT ON COLUMN public.contactos_campos.valor_numero IS 'Valor cuando el tipo de dato es numérico.';
COMMENT ON COLUMN public.contactos_campos.valor_fecha IS 'Valor cuando el tipo de dato es fecha.';
COMMENT ON COLUMN public.contactos_campos.valor_boolean IS 'Valor cuando el tipo de dato es booleano.';
