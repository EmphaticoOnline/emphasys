-- Personas que trabajan en una empresa (contacto): contactos adicionales por contacto.

CREATE TABLE IF NOT EXISTS public.contactos_adicionales (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    empresa_id integer NOT NULL,
    contacto_id integer NOT NULL,

    nombre character varying(150) NOT NULL,
    puesto character varying(100),

    email character varying(150),
    telefono character varying(30),
    telefono_secundario character varying(30),

    observaciones text,

    activo boolean NOT NULL DEFAULT true,

    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),

    CONSTRAINT contactos_adicionales_contacto_empresa_fk
        FOREIGN KEY (empresa_id, contacto_id)
        REFERENCES public.contactos (empresa_id, id)
        ON DELETE CASCADE,

    CONSTRAINT contactos_adicionales_nombre_chk
        CHECK (btrim(nombre) <> '')
);

CREATE INDEX IF NOT EXISTS ix_contactos_adicionales_empresa_contacto
    ON public.contactos_adicionales (empresa_id, contacto_id);

CREATE INDEX IF NOT EXISTS ix_contactos_adicionales_activo
    ON public.contactos_adicionales (empresa_id, contacto_id)
    WHERE activo = true;

CREATE UNIQUE INDEX IF NOT EXISTS ux_contactos_adicionales_email_contacto
    ON public.contactos_adicionales (empresa_id, contacto_id, lower(email))
    WHERE email IS NOT NULL AND activo = true;

DROP TRIGGER IF EXISTS trg_contactos_adicionales_updated_at ON public.contactos_adicionales;
CREATE TRIGGER trg_contactos_adicionales_updated_at
    BEFORE UPDATE ON public.contactos_adicionales
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();
